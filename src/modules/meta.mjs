// -------------------------------------------------------------- helpers
/**
 * Describe a record type.
 *
 * Built-in types are known at load; custom ones belong to a tenant and only
 * exist once somebody defines them, so resolving those needs a repo. The
 * argument is optional because most callers ask about a type they already
 * know is built in, and making all fifty of them pass a repo would have been
 * a lot of churn for nothing.
 */
export function getMeta(recordType, repo = null) {
  const built = RECORDS[recordType];
  if (built) return built;
  if (repo && customRecords.isCustomType(recordType)) return customRecords.describeType(repo, recordType);
  return null;
}
export const listRecordTypes = (repo = null) => [
  ...Object.keys(RECORDS),
  // Only the names are wanted here, so list the types directly rather than
  // through describeAll, which builds every type's full field descriptor
  // (two more queries each) just to have something to read a key off.
  ...(repo ? customRecords.listTypes(repo).map((t) => customRecords.qualified(t.name)) : []),
];
export const fieldsOf = (recordType, repo = null) => getMeta(recordType, repo)?.fields || [];
export const fieldMap = (recordType, repo = null) => Object.fromEntries(fieldsOf(recordType, repo).map((f) => [f.name, f]));
export const isColumn = (recordType, name) => !!fieldMap(recordType)[name] || ['id', 'tenant_id', 'custom'].includes(name);

/** Record types grouped for the navigation sidebar. */
export function navigationGroups() {
  const groups = {};
  for (const [type, m] of Object.entries(RECORDS)) {
    (groups[m.group] ||= []).push({ type, label: m.plural, permission: m.permission, icon: m.icon || null });
  }
  return groups;
}

