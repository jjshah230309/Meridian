// Meridian ERP :: modules/meta
// The record metadata registry.
//
// One declaration per record type drives four things at once:
//   * the generic REST list/detail endpoints,
//   * the saved-search query builder (which columns may be selected/filtered),
//   * the UI's data grids and record forms,
//   * where custom fields are allowed to attach.
// Adding a field in one place makes it appear everywhere, which is the only
// way a system this wide stays consistent.

import { Money, Qty, safeJson } from '../core/util.mjs';
import * as customRecords from './customrecords.mjs';

const F = (name, label, type, opts = {}) => ({ name, label, type, ...opts });
const bool = (v) => v === true || v === 'true' || v === '1' || v === 1;

/** Coerce an inbound value to the storage representation for its field. */
export function coerce(field, v) {
  if (v === undefined) return undefined;
  if (v === null || v === '') return field.type === 'checkbox' ? 0 : null;
  switch (field.type) {
    case 'money': return Money.parse(v);
    case 'qty': return Qty.parse(v);
    case 'number': case 'percent': return Number(v);
    case 'checkbox': return bool(v) ? 1 : 0;
    case 'json': return typeof v === 'string' ? safeJson(v, {}) : v;
    case 'date': return String(v).slice(0, 10);
    default: return v;
  }
}

/**
 * The subset of `patch` a caller is allowed to write to `type`, coerced by
 * each field's declared type.
 *
 * A module with its own update function still has to decide which columns it
 * will set. Hand-kept allow-lists drift: a field gets added to the registry,
 * appears on the form, and is silently dropped on save because nobody
 * remembered the second list. Deriving it from the registry means adding a
 * field is one edit, and the field works.
 */
export function cleanPatch(type, patch, { skip = [], includeReadOnly = false } = {}) {
  const m = getMeta(type);
  if (!m || !patch) return {};
  const blocked = new Set(skip);
  const out = {};
  for (const f of m.fields) {
    if (blocked.has(f.name) || (f.readOnly && !includeReadOnly)) continue;
    if (!(f.name in patch)) continue;
    const v = coerce(f, patch[f.name]);
    if (v !== undefined) out[f.name] = v;
  }
  return out;
}

